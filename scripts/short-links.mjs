#!/usr/bin/env node
// Writes the app short links: public/<slug>/index.html, served as https://wursha.com/<slug>.
// The apps put these in the text they share (a verse, a search result, a book passage, "share the app"),
// so one link works for whoever receives it: Android opens Google Play, iPhone/iPad/Mac the App Store,
// anything else the home page's download table. Store links carry a `share-<slug>` campaign tag, read in
// App Store Connect (App Analytics → Campaigns) and Play Console (acquisition by UTM).
// The slugs are frozen: shipped apps carry them. Add editions, never rename one.
// Run `npm run short-links` after editing the table, and commit the pages.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_STORE_PROVIDER_TOKEN = '119253327'; // as in src/app/shared/catalog.ts

const LINKS = [
    { slug: 'madina', name: 'حَامِلُ القُرْآنِ: مصحف المدينة', play: 'apps.wursha.quran_madina', appStore: 'id1436371392' },
    { slug: 'shmrly', name: 'حَامِلُ القُرْآنِ: مصحف الشمرلي', play: 'apps.wursha.mosshfshmrly', appStore: 'id1434342823' },
    { slug: 'tjwid', name: 'حَامِلُ القُرْآنِ: مصحف التجويد', play: 'apps.wursha.quran_tjwid', appStore: 'id1509386930' },
    { slug: 'warsh', name: 'حَامِلُ القُرْآنِ: مصحف ورش', play: 'apps.wursha.quran_warsh', appStore: 'id1436361790' },
    { slug: 'qalon', name: 'حَامِلُ القُرْآنِ: مصحف قالون', play: 'apps.wursha.quran_qalon', appStore: 'id1437326658' },
    { slug: 'hafs', name: 'حَامِلُ القُرْآنِ: مصحف حفص', play: 'apps.wursha.quran_hafs', appStore: 'id1548150589' },
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function page({ slug, name, play, appStore }) {
    const campaign = `share-${slug}`;
    const referrer = encodeURIComponent(`utm_source=share&utm_medium=app&utm_campaign=${campaign}`);
    const playUrl = `https://play.google.com/store/apps/details?id=${play}&referrer=${referrer}`;
    const appStoreUrl = `https://apps.apple.com/app/${appStore}?pt=${APP_STORE_PROVIDER_TOKEN}&ct=${campaign}&mt=8`;
    const url = `https://wursha.com/${slug}`;
    return `<!doctype html>
<html lang="ar" dir="rtl">
    <head>
        <meta charset="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <meta name="robots" content="noindex" />
        <title>${esc(name)}</title>
        <!-- Generated by scripts/short-links.mjs: edit the table there, not this file. -->
        <meta name="description" content="القرآن كاملاً مع التفاسير والإعراب وأسباب النزول، بلا إنترنت." />
        <link rel="canonical" href="${url}" />
        <meta property="og:type" content="website" />
        <meta property="og:url" content="${url}" />
        <meta property="og:title" content="${esc(name)}" />
        <meta property="og:description" content="القرآن كاملاً مع التفاسير والإعراب وأسباب النزول، بلا إنترنت." />
        <meta property="og:image" content="https://wursha.com/og.jpg" />
        <script>
            (function () {
                var ua = navigator.userAgent;
                var to = /android/i.test(ua)
                    ? ${JSON.stringify(playUrl)}
                    : /iphone|ipad|ipod|macintosh/i.test(ua)
                      ? ${JSON.stringify(appStoreUrl)}
                      : '/';
                location.replace(to);
            })();
        </script>
        <style>
            body { margin: 0; padding: 48px 16px; font: 16px/1.8 system-ui, -apple-system, "Segoe UI", sans-serif; text-align: center; color: #0b2f36; background: #fff; }
            a { color: #094d59; }
        </style>
    </head>
    <body>
        <h1 style="font-size: 20px">${esc(name)}</h1>
        <p>
            <a href="${esc(playUrl)}">Google Play</a> ·
            <a href="${esc(appStoreUrl)}">App Store</a> ·
            <a href="/">wursha.com</a>
        </p>
    </body>
</html>
`;
}

const publicDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'public');
for (const link of LINKS) {
    mkdirSync(join(publicDir, link.slug), { recursive: true });
    writeFileSync(join(publicDir, link.slug, 'index.html'), page(link));
}
console.log(`Wrote ${LINKS.map((l) => `/${l.slug}`).join(' ')}`);
